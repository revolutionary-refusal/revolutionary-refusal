"""Regenerates the human-readable views from the ledger. Never edits FINDINGS.md."""
from __future__ import annotations

import collections
import datetime as dt

from .core import JERUSALEM, ROOT
from .leads import RULES

BANNER = ("<!-- Generated by run.py from the ledger. Do not edit by hand; edits are overwritten. "
          "Curated, reviewed conclusions live in FINDINGS.md. -->\n")


def _cell(text: str) -> str:
    return (text or "").replace("|", "\\|").replace("\n", " ").strip()


def _link(title: str, url: str) -> str:
    return f"[{_cell(title)}]({url})" if url else _cell(title)


def _sort_date(r: dict) -> str:
    """Published date. A date after first sighting (e.g. a contract's future start date) sorts last."""
    seen = r["first_seen"]["utc"][:10]
    pub = r.get("published") or seen
    return pub if pub <= seen else "0000-00-00"


def division_pages(divisions: list[dict], entities: list[dict], records: list[dict], now: dt.datetime) -> None:
    since = now - dt.timedelta(days=30)
    names = {e["id"]: e["name"] for e in entities}
    for d in divisions:
        rows = [r for r in records if d["id"] in r["divisions"]
                and dt.datetime.fromisoformat(r["first_seen"]["utc"]) >= since]
        rows.sort(key=lambda r: (_sort_date(r), r["first_seen"]["utc"]), reverse=True)
        watched = [e for e in entities if d["id"] in e["divisions"]]
        by_class = collections.Counter(r["source_class"] for r in rows)
        out = [BANNER, f"# {d['id']} · {d['title']}\n", f"**Scope.** {d['scope']}\n", "## Standing questions\n"]
        out += [f"- {q}" for q in d["questions"]]
        out += ["", "## Watched entities\n", ", ".join(f"{e['name']}" for e in watched) or "_none_", "",
                f"## Records first seen in the last 30 days ({len(rows)})\n",
                "By kind: " + (", ".join(f"{k} {v}" for k, v in by_class.most_common()) or "none") + "\n",
                "Each row is a document that exists at the link, not a finding. "
                "`signal` is a headline heuristic, shown only to help triage.\n",
                "| Published | Source | Document | Entities | Signal |", "|---|---|---|---|---|"]
        for r in rows[:200]:
            ents = ", ".join(names.get(e, e) for e in r["entities"])
            out.append(f"| {r.get('published') or ''} | {_cell(r['publisher'])} | {_link(r['title'], r['url'])} | "
                       f"{_cell(ents)} | {r.get('title_signal') or ''} |")
        if len(rows) > 200:
            out.append(f"\n_{len(rows) - 200} older rows omitted here; all are in `ledger/`._")
        out += ["", f"See [FINDINGS.md](../../FINDINGS.md) for reviewed conclusions in this division.", ""]
        path = ROOT / "divisions" / d["slug"]
        path.mkdir(parents=True, exist_ok=True)
        (path / "README.md").write_text("\n".join(out))


def leads_page(leads: list[dict], entities: list[dict], now: dt.datetime) -> None:
    names = {e["id"]: e["name"] for e in entities}
    out = [BANNER, "# Open leads (last 30 days)\n",
           f"Generated {now.isoformat()} UTC / {now.astimezone(JERUSALEM):%Y-%m-%d %H:%M} Asia/Jerusalem.\n",
           "A lead is a mechanical reason to look closer. It is not an accusation and not a finding. "
           "Rules are applied identically to every watched entity:\n"]
    out += [f"- **{k}** {v}" for k, v in RULES.items()]
    counts = collections.Counter(l["rule"] for l in leads)
    out += ["", "Leads by rule: " + (", ".join(f"{k} {counts[k]}" for k in RULES if counts[k]) or "none"), "",
            "| Score | Rule | Date | Entities | Document | Signal |", "|---|---|---|---|---|---|"]
    for l in leads[:300]:
        ents = ", ".join(names.get(e, e) for e in l["entities"])
        out.append(f"| {l['score']} | {l['rule']} | {l['date']} | {_cell(ents)} | {_link(l['title'], l['url'])} | {l['signal'] or ''} |")
    (ROOT / "LEADS.md").write_text("\n".join(out) + "\n")


def status_page(run: dict, health: dict) -> None:
    out = [BANNER, "# Collector status\n",
           f"Last run: {run['started']['utc']} UTC · {run['started']['jerusalem']} (Asia/Jerusalem) · "
           f"trigger `{run['trigger']}` · {run['new_records']} new records · ledger total {run['ledger_total']}.\n",
           "| Source | Last result | New this run | Consecutive failures | Last success (UTC) | Error |",
           "|---|---|---|---|---|---|"]
    for name, s in sorted(run["sources"].items()):
        h = health.get(name, {})
        out.append(f"| {name} | {s['status']} | {s.get('new', 0)} | {h.get('consecutive_failures', 0)} | "
                   f"{h.get('last_success', '')} | {_cell(s.get('error', ''))[:160]} |")
    out.append("\nA source failing three runs in a row is flagged in the run log and should be repaired or replaced.\n")
    (ROOT / "STATUS.md").write_text("\n".join(out))
